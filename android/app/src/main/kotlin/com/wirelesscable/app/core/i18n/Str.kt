 * 也不会出现「改了中文忘了改 key」的错位；代价是字典里必须与源码逐字一致。
 * 查不到就原样返回中文：宁可露出中文，也不显示空白或 key。
 *
 * 语言由 [LangState] 决定：默认跟随系统，也可以在设置里显式选中文 / English。
 * `t()` 会读这个可观察状态，切换语言时用到翻译的界面自动重组，不用重建 Activity。
