    /** 当前是否输出英文。设置里选了显式语言时就按它，否则看系统。 */
    val english: Boolean
        get() = when (LangState.mode) {
            LangMode.En -> true
            LangMode.Zh -> false
            LangMode.System -> Locale.getDefault().language.equals("en", ignoreCase = true)
        }

    fun t(zh: String): String {
        if (!english) return zh
        EN[zh]?.let { return it }
        for ((pattern, render) in RULES) {
            val m = pattern.matchEntire(zh) ?: continue
            return render(m)
        }
        return zh
    }

